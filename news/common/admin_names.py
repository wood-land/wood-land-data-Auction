# ============================ 주소 앞쪽 시·군·구 떼어내기 ============================
def peel_sigungu_suffix(seg: str, with_province: bool = False) -> Tuple[str, str]:
    """문자열 끝에 붙은 실제 시·군·구 이름(최대 2단계: '청주시 흥덕구')을 떼어낸다.
    반환: (앞에 남은 문자열, 떼어낸 시군구 문자열). 실제 행정구역 이름만 인정하므로 '사업지구', '집중호우시' 는 걸러진다."""
    rest = seg.rstrip()
    found: List[str] = []
    for _ in range(2):
        hit = ""
        for name in _SIGUNGU_SORTED:
            if rest.endswith(name):
                before = rest[: len(rest) - len(name)]
                # 이름 앞이 한글 글자에 바로 붙어 있으면 더 긴 낱말의 끝부분일 뿐이다 ('사업지구', '집중호우시')
                if before and re.match(r"[가-힣]", before[-1]):
                    continue
                hit = name
                break
        if not hit:
            break
        found.insert(0, hit)
        rest = rest[: len(rest) - len(hit)].rstrip()
        if hit[-1] != "구":      # 시/군 앞에는 더 붙일 것이 없다 (구 -> 시 순서로만 떼어낸다)
            break
    if found and with_province:   # '서울시 중구', '경남 창원시' 처럼 시·도가 바로 앞에 있으면 함께 떼어낸다 ('중구'는 시·도 없이는 어느 도시인지 모른다)
        for key in _PROVINCE_KEYS_SORTED:
            if rest.endswith(key) and not (len(rest) > len(key) and re.match(r"[가-힣]", rest[-len(key) - 1])):
                found.insert(0, key)
                rest = rest[: len(rest) - len(key)].rstrip()
                break
    return rest, " ".join(found)
