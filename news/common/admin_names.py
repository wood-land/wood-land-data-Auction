# ============================ 읍/면 이름 판별 ============================
# '~에 따르면', '~하면' 처럼 면으로 끝나지만 지명이 아닌 낱말 (주소 앞에 붙은 것을 읍/면으로 오인하지 않기 위함)
_NON_PLACE_MYEON = {"따르면", "이르면", "다르면", "모르면", "있으면", "없으면", "한다면", "이라면", "아니면", "그러면", "이러면", "저러면"}
# '하면'은 일부러 뺐다: 실제 면 이름(포항시 '청하면')이 걸려 지명을 잃는다. 동사 '~하면'이 앞에 붙은 경우는
# pnu_resolver 가 읍/면을 뺀 후보도 함께 조회하므로 그쪽에서 복구된다.
_NON_PLACE_MYEON_END = re.compile(r"(?:르면|으면|되면|보면|라면|니면)$")


def is_place_eupmyeon(token: str) -> bool:
    """'XX읍'/'XX면' 이 지명일 가능성이 있는가 (동사형 낱말이면 False)."""
    if not token or token[-1] not in "읍면" or len(token) < 3:
        return False
    if token in _NON_PLACE_MYEON:
        return False
    if token[-1] == "면" and _NON_PLACE_MYEON_END.search(token):
        return False
    return True


